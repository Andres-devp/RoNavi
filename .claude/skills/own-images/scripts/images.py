#!/usr/bin/env python3
"""Own images pipeline: PNG/SVG in the game -> Asphalt -> Open Cloud -> generated Luau ids.

    python images.py check   --game CoinDash          # names, formats, sizes (no tools needed)
    python images.py preview --game CoinDash          # what Asphalt would upload, processed, in .asphalt-debug/
    python images.py sync    --game CoinDash          # dry run: how many uploads and the quota estimate
    python images.py sync    --game CoinDash --yes    # upload (after quota-guard approval)

Layout inside the game:
    assets/images/**/<name>.png|svg|jpg|tga|bmp   your images (input; never modified)
    asphalt.lock.toml                             hashes and asset ids (commit it)
    asphalt.toml                                  regenerated on every run from env vars (gitignored)
    src/shared/Assets/                            Luau module(s) generated by Asphalt

Audio is NOT handled here: own-audio owns it (tighter quota, SoundBank roles). The Asphalt
config only reads assets/images/, so one file is never uploaded by both pipelines.
Standard library only; Asphalt itself comes from the game's toolchain (rokit).
"""

from __future__ import annotations

import os
import re
import shutil
import struct
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[4]
QUOTA = REPO / ".claude" / "skills" / "quota-guard" / "scripts" / "quota.py"

# Keep in step with "asphalt" in ronavi/core/toolchain.py PINS.
ASPHALT_REPO, ASPHALT_VERSION = "jackTabsCode/asphalt", "2.0.2"
IMAGE_SUFFIXES = {".png", ".jpg", ".jpeg", ".bmp", ".tga", ".svg"}
INPUT_DIR = "assets/images"
OUTPUT_DIR = "src/shared/Assets"
MAX_SIDE = 1024  # Roblox downscales larger images; check warns so the art stays sharp
MAX_BYTES = 20 * 1024 * 1024
NAME_RE = re.compile(r"^[a-z0-9][a-z0-9_-]*$")
GITIGNORE = ["asphalt.toml", ".asphalt-debug/"]
DRY_RUN_RE = re.compile(r"(\d+)\s+(?:new|changed|modified)?\s*assets?", re.IGNORECASE)


# --------------------------------------------------------------------------- paths

def games_home() -> Path:
    env = os.environ.get("ROBLOX_GAMES_HOME")
    return Path(env).expanduser() if env else REPO / "games"


def game_root(game: str) -> Path:
    root = Path(game) if Path(game).is_dir() else games_home() / game
    if not root.is_dir():
        raise SystemExit(f"game folder not found: {root} (set ROBLOX_GAMES_HOME or pass a path)")
    return root


def images(root: Path) -> list[Path]:
    src = root / INPUT_DIR
    if not src.is_dir():
        raise SystemExit(f"no image folder: {src}  (put your PNG/SVG there)")
    return sorted(p for p in src.rglob("*") if p.is_file() and not p.name.startswith("."))


# --------------------------------------------------------------------------- check

def png_size(path: Path) -> tuple[int, int] | None:
    with path.open("rb") as fh:
        head = fh.read(24)
    if len(head) < 24 or head[:8] != b"\x89PNG\r\n\x1a\n":
        return None
    return struct.unpack(">II", head[16:24])


def problems_for(path: Path, root: Path) -> list[str]:
    issues = []
    rel = path.relative_to(root / INPUT_DIR)
    if path.suffix.lower() not in IMAGE_SUFFIXES:
        issues.append("not an image Asphalt uploads here (audio goes through own-audio)")
    for part in [*rel.parts[:-1], path.stem]:
        if not NAME_RE.match(part):
            issues.append(f"'{part}': use lowercase letters, digits, '-' or '_' (it becomes a key in the Luau module)")
            break
    if path.stat().st_size > MAX_BYTES:
        issues.append(f"{path.stat().st_size / 1e6:.1f} MB > 20 MB")
    size = png_size(path) if path.suffix.lower() == ".png" else None
    if size and max(size) > MAX_SIDE:
        issues.append(f"{size[0]}x{size[1]} px: Roblox shows at most {MAX_SIDE} px per side, export it smaller")
    return issues


def cmd_check(a) -> int:
    root = game_root(a.game)
    bad = 0
    for p in images(root):
        issues = problems_for(p, root)
        bad += bool(issues)
        size = png_size(p) if p.suffix.lower() == ".png" else None
        desc = f"{size[0]}x{size[1]}" if size else p.suffix.lower().lstrip(".")
        print(f"{'ok ' if not issues else '!! '}{p.relative_to(root / INPUT_DIR).as_posix():48} {desc}")
        for i in issues:
            print(f"     - {i}")
    print(f"\n{bad} file(s) with issues")
    return 1 if bad else 0


# --------------------------------------------------------------------------- setup

def creator() -> tuple[str, str]:
    group, user = os.environ.get("ROBLOX_GROUP_ID"), os.environ.get("ROBLOX_USER_ID")
    if group:
        return "group", group
    if user:
        return "user", user
    raise SystemExit("set ROBLOX_USER_ID or ROBLOX_GROUP_ID (the creator that owns the uploads): "
                     "setx ROBLOX_USER_ID <id> on Windows, export in your shell profile elsewhere")


def asphalt_toml(kind: str, creator_id: str) -> str:
    return (
        "# GENERATED by the own-images skill on every run, from ROBLOX_USER_ID / ROBLOX_GROUP_ID.\n"
        "# Gitignored on purpose: edit images.py, not this file. Commit asphalt.lock.toml instead.\n"
        f'[creator]\ntype = "{kind}"\nid = {int(creator_id)}\n\n'
        '[codegen]\nstyle = "nested"\nstrip_extensions = true\n\n'
        f'[inputs.images]\npath = "{INPUT_DIR}/**/*"\noutput_path = "{OUTPUT_DIR}"\n')


def manifest(root: Path) -> Path | None:
    return next((root / m for m in ("rokit.toml", "aftman.toml") if (root / m).is_file()), None)


def ensure_asphalt(root: Path) -> None:
    """Asphalt in the game's toolchain manifest, trusted and installed."""
    path = manifest(root)
    if path is None:
        raise SystemExit(f"{root} has no aftman.toml / rokit.toml: scaffold the game with roblox-code first")
    text = path.read_text(encoding="utf-8")
    if not re.search(r"(?mi)^\s*asphalt\s*=", text):
        line = f'asphalt = "{ASPHALT_REPO}@{ASPHALT_VERSION}"'
        path.write_text(text.rstrip("\n") + "\n" + line + "\n", encoding="utf-8")
        print(f"added to {path.name}: {line}")
    rokit = shutil.which("rokit")
    if not rokit:
        raise SystemExit("rokit not found: install it (winget install Rojo.Rokit), then rerun")
    subprocess.run([rokit, "trust", ASPHALT_REPO], cwd=root, capture_output=True)
    res = subprocess.run([rokit, "install"], cwd=root, capture_output=True, text=True)
    if res.returncode != 0:
        raise SystemExit("rokit install failed:\n" + (res.stdout + res.stderr).strip()[-800:])


def ensure_gitignore(root: Path) -> None:
    gi = root / ".gitignore"
    lines = gi.read_text(encoding="utf-8").splitlines() if gi.exists() else []
    missing = [x for x in GITIGNORE if x not in lines]
    if missing:
        block = ["", "# own-images (Asphalt): regenerated files", *missing] if lines else missing
        gi.write_text("\n".join([*lines, *block]).strip("\n") + "\n", encoding="utf-8")


def setup(root: Path) -> str:
    kind, cid = creator()
    if not cid.isdigit():
        raise SystemExit(f"ROBLOX_{kind.upper()}_ID must be a number")
    ensure_asphalt(root)
    ensure_gitignore(root)
    (root / "asphalt.toml").write_text(asphalt_toml(kind, cid), encoding="utf-8")
    exe = shutil.which("asphalt", path=os.pathsep.join([str(Path.home() / ".rokit" / "bin"),
                                                         os.environ.get("PATH", "")]))
    if not exe:
        raise SystemExit("asphalt not found after rokit install: open a new terminal (rokit self-install adds "
                         "~/.rokit/bin to PATH) and rerun")
    return exe


def asphalt(exe: str, root: Path, *args: str, env: dict | None = None) -> subprocess.CompletedProcess:
    return subprocess.run([exe, *args], cwd=root, capture_output=True, text=True, encoding="utf-8",
                          errors="replace", env=env)


def pending_uploads(exe: str, root: Path) -> int:
    """How many images Asphalt would upload, from `sync cloud --dry-run` (no key, no upload)."""
    res = asphalt(exe, root, "sync", "cloud", "--dry-run")
    out = (res.stdout + res.stderr).strip()
    if res.returncode == 0:
        return 0
    m = re.search(r"Dry run:(.*)would be synced", out, re.IGNORECASE)
    if not m:
        raise SystemExit("asphalt dry run failed:\n" + out[-800:])
    return sum(int(n) for n in DRY_RUN_RE.findall(m.group(1))) or 1


# --------------------------------------------------------------------------- preview / sync

def quota(*args: str) -> int:
    sys.stdout.flush()
    return subprocess.run([sys.executable, str(QUOTA), *args]).returncode


def cmd_preview(a) -> int:
    root = game_root(a.game)
    exe = setup(root)
    res = asphalt(exe, root, "sync", "debug")
    print((res.stdout + res.stderr).strip())
    print(f"\nprocessed copies (alpha bleed, SVG -> PNG) in {root / '.asphalt-debug'}; nothing was uploaded")
    return res.returncode


def cmd_sync(a) -> int:
    root = game_root(a.game)
    if cmd_check(a) and not a.ignore_check:
        print("\nfix the files marked !! first (or rerun with --ignore-check)")
        return 1
    exe = setup(root)
    count = pending_uploads(exe, root)
    if count == 0:
        print("\nnothing to upload: every image already has an asset id for its current hash")
        return 0
    print(f"\n{count} image(s) to upload")
    if quota("estimate", "opencloud-assets", "--op", "image-upload", "--count", str(count)) == 2 \
            and not a.allow_over_quota:
        print("would exceed the Open Cloud assets quota: ask the user (quota-guard) or upload fewer files")
        return 2
    if not a.yes:
        print("dry run. After the user approves (quota-guard), rerun with --yes")
        return 0

    api_key = os.environ.get("ROBLOX_API_KEY")
    if not api_key:
        raise SystemExit("ROBLOX_API_KEY is not set (Open Cloud key with asset:read and asset:write)")
    env = dict(os.environ, ASPHALT_API_KEY=api_key)  # never on the command line, where ps could show it
    res = asphalt(exe, root, "sync", "cloud", env=env)
    print((res.stdout + res.stderr).strip())
    left = pending_uploads(exe, root)
    done = max(count - left, 0)
    if done:
        quota("log", "opencloud-assets", "--op", "image-upload", "--count", str(done), "--note", f"{root.name} images")
    if res.returncode != 0:
        print(f"\nasphalt failed after {done} upload(s); the lockfile keeps those, rerun to continue")
        return 1
    print(f"\n{done} uploaded. Commit asphalt.lock.toml and {OUTPUT_DIR}/ in the game's repo.")
    return 0


# --------------------------------------------------------------------------- main

def main() -> int:
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    import argparse

    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    for name in ("check", "preview", "sync"):
        p = sub.add_parser(name)
        p.add_argument("--game", required=True, help="game name under ROBLOX_GAMES_HOME, or a path")
        if name == "sync":
            p.add_argument("--yes", action="store_true", help="actually upload (default: dry run)")
            p.add_argument("--ignore-check", action="store_true", help="upload even with files marked !!")
            p.add_argument("--allow-over-quota", action="store_true",
                           help="only after the user explicitly accepts going over")
    a = ap.parse_args()
    return {"check": cmd_check, "preview": cmd_preview, "sync": cmd_sync}[a.cmd](a)


if __name__ == "__main__":
    sys.exit(main())
